// Stable actor/static face ordering helpers.
//
// v15 keeps the v13 canonical front-space support-only actor relation, and
// disables stable local terrain demerge by default. Local demerge can still be
// re-enabled explicitly with localStorage stableActorSortDemerge=1 for diagnostics.
//
// v13 intentionally removes the rotation-specific terrain/top/side override
// stack that was added while debugging stair occlusion. That stack rewrote
// many nearby static faces whenever the player approached stairs, so side
// rotations corrupted the stair blocks themselves. The stable path now reuses
// the canonical front-view ordering model for every view: static packets and
// the player keep the sortKey/tie generated by the view-rotation core, then we
// apply only the universal support-floor guard that keeps the actor's own floor
// tile before the actor. No separate rules for rotation 1/2/3 live here.
(function () {
  if (typeof window === 'undefined') return;

  var EPS = 1e-4;
  var __stableActorSortProbeCount = 0;
  var __lastStableActorSortProbeSignature = '';

  function safeNumber(value, fallback) {
    var n = Number(value);
    return Number.isFinite(n) ? n : Number(fallback || 0);
  }

  function readLocalStorageFlag(name) {
    try {
      if (typeof localStorage === 'undefined') return null;
      return localStorage.getItem(name);
    } catch (_) {
      return null;
    }
  }

  function isStableActorSortEnabled() {
    return readLocalStorageFlag('legacyActorInteractionReplacement') !== '1';
  }

  function isStableActorSortProbeEnabled() {
    var flag = readLocalStorageFlag('actorSortDiag');
    return flag === '1' || flag === 'true' || readLocalStorageFlag('terrainPlayerDiag') === '1' || readLocalStorageFlag('terrainSortDiag') === '1';
  }

  function roundDiagNumber(value, digits) {
    var n = Number(value);
    if (!Number.isFinite(n)) return null;
    var scale = Math.pow(10, digits == null ? 3 : digits);
    return Math.round(n * scale) / scale;
  }

  function normalizeViewRotationLocal(value) {
    var n = Math.round(safeNumber(value, 0));
    return ((n % 4) + 4) % 4;
  }

  function rotatePointForView(point, viewRotation) {
    var x = safeNumber(point && point.x, 0);
    var y = safeNumber(point && point.y, 0);
    switch (normalizeViewRotationLocal(viewRotation)) {
      case 1: return { x: y, y: -x };
      case 2: return { x: -x, y: -y };
      case 3: return { x: -y, y: x };
      default: return { x: x, y: y };
    }
  }

  function summarizeDiagCell(cell) {
    if (!cell || typeof cell !== 'object') return null;
    var z = safeNumber(cell.z, 0);
    var h = safeNumber(cell.h != null ? cell.h : 1, 1);
    return {
      id: cell.id != null ? String(cell.id).slice(0, 120) : null,
      instanceId: cell.instanceId != null ? String(cell.instanceId).slice(0, 120) : null,
      prefabId: cell.prefabId != null ? String(cell.prefabId).slice(0, 120) : null,
      x: roundDiagNumber(cell.x, 3),
      y: roundDiagNumber(cell.y, 3),
      z: roundDiagNumber(z, 3),
      w: roundDiagNumber(cell.w != null ? cell.w : 1, 3),
      d: roundDiagNumber(cell.d != null ? cell.d : 1, 3),
      h: roundDiagNumber(h, 3),
      topZ: roundDiagNumber(z + h, 3),
      generatedBy: cell.generatedBy != null ? String(cell.generatedBy).slice(0, 80) : null,
      terrainBand: cell.terrainBand != null ? String(cell.terrainBand).slice(0, 80) : null
    };
  }

  function summarizeDiagPlayer(player) {
    player = player && typeof player === 'object' ? player : {};
    return {
      x: roundDiagNumber(player.x, 3),
      y: roundDiagNumber(player.y, 3),
      z: roundDiagNumber(player.z, 3),
      visualZ: roundDiagNumber(player.visualZ, 3),
      renderSortZ: roundDiagNumber(player.renderSortZ, 3),
      moving: !!player.moving,
      dir: player.dir != null ? String(player.dir) : null,
      jumpActive: !!(player.jump && player.jump.active),
      jumpMode: player.jump && player.jump.mode != null ? String(player.jump.mode) : null,
      jumpT: roundDiagNumber(player.jump && player.jump.t, 3),
      jumpFromZ: roundDiagNumber(player.jump && player.jump.fromZ, 3),
      jumpToZ: roundDiagNumber(player.jump && player.jump.toZ, 3)
    };
  }

  function getPacketMemberCells(packet) {
    var out = [];
    if (!packet || typeof packet !== 'object') return out;
    var members = Array.isArray(packet.actorInteractionMemberDescriptors) && packet.actorInteractionMemberDescriptors.length
      ? packet.actorInteractionMemberDescriptors
      : (Array.isArray(packet.members) && packet.members.length ? packet.members : [packet.box || packet.cell || null]);
    for (var i = 0; i < members.length; i++) {
      var m = members[i];
      var cell = m && (m.cell || m.box || m);
      if (cell && typeof cell === 'object') out.push(cell);
    }
    return out;
  }

  function cellBounds(cell) {
    var x = Math.floor(safeNumber(cell && cell.x, 0));
    var y = Math.floor(safeNumber(cell && cell.y, 0));
    var z = safeNumber(cell && cell.z, 0);
    var w = Math.max(1, safeNumber(cell && cell.w != null ? cell.w : 1, 1));
    var d = Math.max(1, safeNumber(cell && cell.d != null ? cell.d : 1, 1));
    var h = Math.max(1, safeNumber(cell && cell.h != null ? cell.h : 1, 1));
    return { x: x, y: y, z: z, w: w, d: d, h: h, topZ: z + h };
  }

  function footOwnsCellTop(player, cell) {
    if (!player || !cell) return false;
    var px = safeNumber(player.x, NaN);
    var py = safeNumber(player.y, NaN);
    var pz = safeNumber(player.renderSortZ != null ? player.renderSortZ : player.z, NaN);
    if (!Number.isFinite(px) || !Number.isFinite(py) || !Number.isFinite(pz)) return false;
    var b = cellBounds(cell);
    if (Math.abs(b.topZ - pz) > 0.001) return false;
    // Half-open ownership makes adjacent cells deterministic: exactly one cell
    // owns a player foot position on an internal tile boundary.
    return px >= b.x - EPS && px < b.x + b.w - EPS
      && py >= b.y - EPS && py < b.y + b.d - EPS;
  }

  function packetActsAsSupportTop(packet, player) {
    if (!packet || packet.kind !== 'static-world-face-packet') return false;
    if (String(packet.semanticFace || '') !== 'top') return false;
    var cells = getPacketMemberCells(packet);
    for (var i = 0; i < cells.length; i++) {
      if (footOwnsCellTop(player, cells[i])) return true;
    }
    return false;
  }

  function packetLooksTerrain(packet, cells) {
    if (!packet || typeof packet !== 'object') return false;
    if (packet.terrainMaterialMergeKey != null || packet.terrainMaterialId != null || packet.terrainMaterialLabel != null) return true;
    var packetText = String(packet.materialType || packet.terrainBand || packet.prefabId || packet.instanceId || '').toLowerCase();
    if (packetText.indexOf('terrain') >= 0) return true;
    var list = Array.isArray(cells) ? cells : getPacketMemberCells(packet);
    for (var i = 0; i < list.length; i++) {
      var c = list[i];
      if (!c) continue;
      if (c.generatedBy === 'terrain-generator' || c.terrain === true || c.isTerrain === true) return true;
      if (c.terrainBand != null || c.terrainMaterialId != null || c.terrainMaterialMergeKey != null) return true;
      var cellText = String(c.materialType || c.prefabId || c.instanceId || '').toLowerCase();
      if (cellText.indexOf('terrain') >= 0) return true;
    }
    return false;
  }

  function isStableDemergeEnabled() {
    return readLocalStorageFlag('stableActorSortDemerge') === '1' || readLocalStorageFlag('experimentalStableLocalDemerge') === '1';
  }

  function shouldDemergeStaticPacket(packet) {
    if (!isStableActorSortEnabled() || !isStableDemergeEnabled()) return false;
    if (!packet || packet.kind !== 'static-world-face-packet') return false;
    var face = String(packet.semanticFace || '');
    if (face !== 'top' && face !== 'east' && face !== 'south' && face !== 'west' && face !== 'north') return false;
    var members = Array.isArray(packet.actorInteractionMemberDescriptors) ? packet.actorInteractionMemberDescriptors : [];
    if (members.length <= 1) return false;
    if (readLocalStorageFlag('stableActorSortDemergeAll') === '1') return true;
    return packetLooksTerrain(packet, members);
  }

  function computePlayerSortMeta(player, viewRotation, helpers) {
    var h = helpers && typeof helpers.computePlayerSortMeta === 'function'
      ? helpers.computePlayerSortMeta(player, viewRotation)
      : null;
    if (h && Number.isFinite(Number(h.sortKey))) return h;
    var pz = safeNumber(player && player.renderSortZ != null ? player.renderSortZ : player && player.z, 0);
    var rotated = rotatePointForView({ x: player && player.x, y: player && player.y }, viewRotation);
    return {
      sortKey: rotated.x + rotated.y + pz + 0.0007,
      tie: 700000 + (pz * 100000) + (rotated.y * 100) + rotated.x
    };
  }

  function summarizePacket(packet, helpers) {
    if (helpers && typeof helpers.summarizeRenderable === 'function') {
      try { return helpers.summarizeRenderable(packet); } catch (_) {}
    }
    return {
      id: packet && packet.id || null,
      kind: packet && packet.kind || null,
      semanticFace: packet && packet.semanticFace || null,
      sortKey: packet && packet.sortKey != null ? Number(packet.sortKey) : null,
      tie: packet && packet.tie != null ? Number(packet.tie) : null,
      actorStableSortRelation: packet && packet.actorStableSortRelation || null,
      firstCell: summarizeDiagCell(getPacketMemberCells(packet)[0])
    };
  }

  function compareByDomain(a, b, helpers) {
    if (helpers && typeof helpers.compareRenderables === 'function') return helpers.compareRenderables(a, b);
    var ak = safeNumber(a && a.sortKey, 0);
    var bk = safeNumber(b && b.sortKey, 0);
    if (Math.abs(ak - bk) > 1e-9) return ak - bk;
    return safeNumber(a && a.tie, 0) - safeNumber(b && b.tie, 0);
  }

  function emitDiag(tag, payload, helpers) {
    if (helpers && typeof helpers.emitDiag === 'function') {
      try { helpers.emitDiag(tag, payload || {}, { maxCount: 6000 }); } catch (_) {}
    }
  }

  function emitStableActorSortProbe(payload, helpers) {
    if (!isStableActorSortProbeEnabled()) return;
    __stableActorSortProbeCount += 1;
    var signature = '';
    try {
      signature = [payload.viewRotation, payload.staticRenderableCount, payload.overrideCount, payload.player && payload.player.x, payload.player && payload.player.y, payload.player && payload.player.renderSortZ].join('|');
    } catch (_) { signature = String(__stableActorSortProbeCount); }
    if (__stableActorSortProbeCount > 20 && signature === __lastStableActorSortProbeSignature && (__stableActorSortProbeCount % 60) !== 0) return;
    __lastStableActorSortProbeSignature = signature;
    emitDiag('stable-player-face-sort-probe', payload, helpers);
  }

  function applySupportTopSortOverride(packet, playerSortMeta) {
    var originalTie = safeNumber(packet && packet.tie, 0);
    return Object.assign({}, packet, {
      sortKey: safeNumber(playerSortMeta.sortKey, 0) - 0.0012,
      tie: safeNumber(playerSortMeta.tie, 700000) - 120 + ((Math.abs(originalTie) % 1000) * 0.000001),
      actorStableSortOverride: true,
      actorStableSortRelation: 'support-top-before-player',
      actorInteractionSupportTopSortOverride: true,
      actorInteractionSupportFloor: true,
      actorInteractionGroupSortRelation: 'support-top-before-player',
      actorInteractionGroupFootprintMode: 'canonical-front-space-support-top-only',
      renderPath: String(packet && packet.renderPath || 'static-world-chunk-packet') + '+canonical-support-top-sort'
    });
  }

  function applyStablePlayerFaceSort(options) {
    var safe = options && typeof options === 'object' ? options : {};
    var list = Array.isArray(safe.staticRenderables) ? safe.staticRenderables : [];
    var player = safe.player && typeof safe.player === 'object' ? safe.player : null;
    var helpers = safe.helpers || {};
    var viewRotation = safe.viewRotation;
    if (!list.length || !player || !isStableActorSortEnabled()) {
      return { staticRenderables: list, overrideCount: 0, overrideSamples: [], mode: isStableActorSortEnabled() ? 'canonical-front-space-no-player' : 'legacy-disabled' };
    }

    var playerSortMeta = computePlayerSortMeta(player, viewRotation, helpers);
    var out = list.slice();
    var overrideCount = 0;
    var samples = [];
    var supportSamples = [];

    for (var i = 0; i < out.length; i++) {
      var packet = out[i];
      if (!packetActsAsSupportTop(packet, player)) continue;
      var clone = applySupportTopSortOverride(packet, playerSortMeta);
      out[i] = clone;
      overrideCount += 1;
      if (samples.length < 16) samples.push(summarizePacket(clone, helpers));
      if (supportSamples.length < 16) supportSamples.push({ index: i, packet: summarizePacket(clone, helpers) });
    }

    if (overrideCount > 0) out.sort(function (a, b) { return compareByDomain(a, b, helpers); });

    emitStableActorSortProbe({
      version: 'stable-actor-sort-probe-v15-no-local-demerge-20260508',
      functionPath: 'actor-support-top-sort-override.applyPlayerSupportTopSortOverrideToRenderables -> __ACTOR_SORT_STABLE__.applyStablePlayerFaceSort',
      behaviorNote: 'canonical front-space reuse: no rotation-specific terrain/top/side rules. Static packets and player use the same view-rotation sortKey/tie model for every direction; only the actor-owned support top is forced before player.',
      viewRotation: viewRotation,
      normalizedViewRotation: normalizeViewRotationLocal(viewRotation),
      player: summarizeDiagPlayer(player),
      playerSortMeta: { sortKey: roundDiagNumber(playerSortMeta && playerSortMeta.sortKey, 6), tie: roundDiagNumber(playerSortMeta && playerSortMeta.tie, 6) },
      staticRenderableCount: list.length,
      outputStaticRenderableCount: out.length,
      overrideCount: overrideCount,
      counts: {
        supportTop: overrideCount,
        disabledLegacyTerrainOverrideStack: true,
        nearbySameLevelTop: 0,
        highTerrainTop: 0,
        sameLevelTerrainSide: 0,
        narrowHighSide: 0,
        cellGroupCandidate: 0,
        overrideCellGroupPacket: 0
      },
      supportSamples: supportSamples,
      overrideSamples: samples
    }, helpers);

    if (overrideCount > 0) {
      emitDiag('stable-support-top-sort-override', {
        viewRotation: viewRotation,
        mode: 'canonical-front-space-support-top-only',
        player: helpers && typeof helpers.summarizePlayer === 'function' ? helpers.summarizePlayer(player) : { x: player.x, y: player.y, z: player.z },
        inputStaticRenderableCount: list.length,
        outputStaticRenderableCount: out.length,
        overrideCount: overrideCount,
        samples: samples
      }, helpers);
    }

    return { staticRenderables: out, overrideCount: overrideCount, overrideSamples: samples, mode: 'canonical-front-space-support-top-only' };
  }

  // Compatibility exports kept for tests/diagnostics. They are deliberately
  // inert in v13 so future changes cannot accidentally resurrect the duplicate
  // per-rotation terrain override stack.
  function packetActsAsNearbySameLevelTop() { return false; }
  function topZMatchesPlayerTopSortLevels() { return false; }
  function getPlayerTopSortLevels(player) {
    var z = safeNumber(player && player.renderSortZ != null ? player.renderSortZ : player && player.z, 0);
    return [z];
  }
  function isExperimentalActorSideSortEnabled() { return false; }
  function shouldApplySameLevelTerrainSideBeforePlayer() { return false; }
  function shouldApplyHighTerrainTopBeforePlayer() { return false; }
  function shouldApplyNarrowHighSideSortOverride() { return false; }
  function classifySingleCellSideAgainstPlayer() { return 'none'; }

  try { console.log('[actor-sort-version]', 'stable-actor-sort-v15-canonical-front-space-no-local-demerge-20260508'); } catch (_) {}

  window.__ACTOR_SORT_STABLE__ = {
    version: 'stable-actor-sort-v15-canonical-front-space-no-local-demerge-20260508',
    isEnabled: isStableActorSortEnabled,
    getPacketMemberCells: getPacketMemberCells,
    packetLooksTerrain: packetLooksTerrain,
    isStableDemergeEnabled: isStableDemergeEnabled,
    shouldDemergeStaticPacket: shouldDemergeStaticPacket,
    packetActsAsSupportTop: packetActsAsSupportTop,
    packetActsAsNearbySameLevelTop: packetActsAsNearbySameLevelTop,
    getPlayerTopSortLevels: getPlayerTopSortLevels,
    topZMatchesPlayerTopSortLevels: topZMatchesPlayerTopSortLevels,
    isExperimentalActorSideSortEnabled: isExperimentalActorSideSortEnabled,
    shouldApplySameLevelTerrainSideBeforePlayer: shouldApplySameLevelTerrainSideBeforePlayer,
    shouldApplyHighTerrainTopBeforePlayer: shouldApplyHighTerrainTopBeforePlayer,
    shouldApplyNarrowHighSideSortOverride: shouldApplyNarrowHighSideSortOverride,
    classifySingleCellSideAgainstPlayer: classifySingleCellSideAgainstPlayer,
    applyStablePlayerFaceSort: applyStablePlayerFaceSort
  };
})();
